import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const require = createRequire(new URL("./pathfinding/package.json", import.meta.url));
const { build } = require("esbuild");

await build({
  absWorkingDir: fileURLToPath(new URL("../../", import.meta.url)),
  entryPoints: [fileURLToPath(new URL("./pathfinding/dist/index.js", import.meta.url))],
  outfile: fileURLToPath(new URL("./pathfinder.cjs", import.meta.url)),
  bundle: true,
  packages: "external",
  platform: "node",
  format: "cjs",
  target: "node22",
  banner: {
    js: "// Generated by pnpm build:pathfinder. GPL-3.0-only; includes MIT Rewrite code and adapted Botcraft code. See COPYING, THIRD-PARTY-NOTICES.md and pathfinder-source.json.",
  },
});

// Ship the corresponding editable source with the standalone GPL worker and
// the embedded installer. No dependency trees or build outputs go in this file.
const root = fileURLToPath(new URL("./", import.meta.url));
const files = {};
async function collect(relative) {
  for (const entry of await readdir(path.join(root, relative), { withFileTypes: true })) {
    const next = path.posix.join(relative, entry.name);
    if (entry.isDirectory()) await collect(next);
    else files[next] = await readFile(path.join(root, next), "utf8");
  }
}
